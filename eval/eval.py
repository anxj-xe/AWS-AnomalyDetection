"""
Evaluation script for the detector used by main.py.

This file does NOT modify main.py.
It evaluates AWSAnomalyDetector using the same labeled benchmark
generated by AWSDataSimulator.

Run from project root:
    python eval_main.py

Or:
    python eval_main.py --file data/aws_benchmark_dataset.csv

The benchmark contains ground-truth fields:
    ground_truth_label
    faulty_sensor
    is_sensor_fault

The detector is evaluated on:
    - sensor-fault detection
    - weather-event rejection
    - anomaly type classification
    - faulty sensor identification
"""

import argparse
import os
import sys
from collections import Counter

import numpy as np
import pandas as pd
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report,
)

# Make imports work when this file is run directly from the project root.
PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))
if PROJECT_DIR not in sys.path:
    sys.path.insert(0, PROJECT_DIR)

from src.data_simulator import AWSDataSimulator
from src.detector import AWSAnomalyDetector


DEFAULT_FILE = os.path.join(
    PROJECT_DIR,
    "data",
    "aws_benchmark_dataset.csv",
)


def generate_benchmark():
    """
    Generate the same type of labeled benchmark used by main.py.
    """
    print("[INFO] Generating labeled AWS benchmark...")
    simulator = AWSDataSimulator(seed=42)

    df = simulator.generate_historical_dataset(
        days=5,
        interval_minutes=1,
        inject_anomalies=True,
    )

    print(f"[INFO] Generated {len(df)} observations.")
    return df


def load_dataset(file_path):
    if not os.path.exists(file_path):
        raise FileNotFoundError(
            f"Dataset not found:\n{file_path}\n\n"
            f"Run without --file to generate the benchmark automatically."
        )

    print(f"[INFO] Loading: {file_path}")
    df = pd.read_csv(file_path)

    required = {
        "timestamp",
        "temperature",
        "pressure",
        "humidity",
    }

    missing = required - set(df.columns)

    if missing:
        raise ValueError(
            "Dataset is missing required columns: "
            + ", ".join(sorted(missing))
        )

    return df


def ensure_ground_truth(df):
    """
    If the supplied file is not labeled, generate a labeled benchmark
    instead of inventing labels.
    """
    required_truth = {
        "ground_truth_label",
        "faulty_sensor",
        "is_sensor_fault",
    }

    missing = required_truth - set(df.columns)

    if missing:
        raise ValueError(
            "This evaluation requires a labeled benchmark containing: "
            + ", ".join(sorted(required_truth))
            + f"\nMissing: {', '.join(sorted(missing))}"
        )

    return df


def run_detector(df):
    """
    Run exactly the AWSAnomalyDetector used by main.py.

    main.py's evaluate_csv_file() trains on the first 1000 rows,
    then calls process_dataframe() on the complete input.
    This function follows that same detector workflow.
    """
    detector = AWSAnomalyDetector()

    baseline_n = min(1000, len(df))

    print(f"[INFO] Training detector on first {baseline_n} rows...")
    detector.fit(df.head(baseline_n))

    print("[INFO] Processing benchmark sequentially...")
    reports = detector.process_dataframe(df)

    return reports


def reports_to_dataframe(df, reports):
    rows = []

    for truth, report in zip(df.itertuples(index=False), reports):
        rows.append({
            "timestamp": report.timestamp,
            "temperature": report.temperature,
            "pressure": report.pressure,
            "humidity": report.humidity,

            "ground_truth_label": getattr(
                truth, "ground_truth_label", "UNKNOWN"
            ),
            "ground_truth_sensor_fault": bool(
                getattr(truth, "is_sensor_fault", False)
            ),
            "ground_truth_faulty_sensor": getattr(
                truth, "faulty_sensor", None
            ),

            "predicted_anomaly": bool(report.is_anomaly),
            "predicted_weather_event": bool(report.is_weather_event),
            "predicted_anomaly_type": report.anomaly_type,
            "predicted_faulty_sensor": report.faulty_sensor,

            "confidence": float(report.confidence),
            "severity": float(report.severity),
            "explanation": report.explanation,
        })

    return pd.DataFrame(rows)


def print_detection_metrics(result):
    y_true = result["ground_truth_sensor_fault"].astype(int)
    y_pred = result["predicted_anomaly"].astype(int)

    cm = confusion_matrix(y_true, y_pred, labels=[0, 1])

    accuracy = accuracy_score(y_true, y_pred)
    precision = precision_score(
        y_true,
        y_pred,
        zero_division=0,
    )
    recall = recall_score(
        y_true,
        y_pred,
        zero_division=0,
    )
    f1 = f1_score(
        y_true,
        y_pred,
        zero_division=0,
    )

    tn, fp, fn, tp = cm.ravel()

    total_faults = int(y_true.sum())
    caught = int(tp)

    catch_rate = (
        100.0 * caught / total_faults
        if total_faults
        else 0.0
    )

    print("\n" + "=" * 75)
    print("  MAIN.PY / AWSANOMALYDETECTOR EVALUATION")
    print("=" * 75)

    print(f"Total observations : {len(result)}")
    print(f"True sensor faults : {total_faults}")
    print(f"Detected faults    : {int(y_pred.sum())}")

    print("\nConfusion Matrix")
    print("                  Pred Normal   Pred Fault")
    print(
        f"True Normal       {tn:11d}   {fp:10d}"
    )
    print(
        f"True Fault        {fn:11d}   {tp:10d}"
    )

    print("\nOverall Detection Metrics")
    print(f"Accuracy           : {accuracy:.4f} ({accuracy * 100:.2f}%)")
    print(f"Precision          : {precision:.4f} ({precision * 100:.2f}%)")
    print(f"Recall / Catch     : {recall:.4f} ({recall * 100:.2f}%)")
    print(f"F1 Score           : {f1:.4f}")
    print(f"Caught anomalies   : {caught}/{total_faults} ({catch_rate:.2f}%)")

    false_alarm_rate = (
        100.0 * fp / (tn + fp)
        if (tn + fp)
        else 0.0
    )

    print(
        f"False alarm rate   : {false_alarm_rate:.2f}%"
    )

    return {
        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "catch_rate": catch_rate,
        "false_alarm_rate": false_alarm_rate,
        "tn": tn,
        "fp": fp,
        "fn": fn,
        "tp": tp,
    }


def print_weather_event_metrics(result):
    """
    Genuine weather events are NOT sensor faults in the simulator.
    Check how often the detector correctly leaves them unalarmed.
    """
    weather = result[
        result["ground_truth_label"] == "GENUINE_WEATHER_EVENT"
    ].copy()

    if weather.empty:
        print("\nNo genuine weather-event rows found.")
        return

    false_sensor_alarm = int(
        weather["predicted_anomaly"].sum()
    )

    correctly_disentangled = int(
        (
            (~weather["predicted_anomaly"])
            & weather["predicted_weather_event"]
        ).sum()
    )

    weather_rejection_rate = (
        100.0
        * (len(weather) - false_sensor_alarm)
        / len(weather)
    )

    print("\n" + "=" * 75)
    print("  GENUINE WEATHER EVENT DISENTANGLING")
    print("=" * 75)

    print(f"Weather-event observations : {len(weather)}")
    print(f"False sensor alarms        : {false_sensor_alarm}")
    print(
        f"Correctly identified weather: "
        f"{correctly_disentangled}"
    )
    print(
        f"Weather rejection rate     : "
        f"{weather_rejection_rate:.2f}%"
    )


def print_anomaly_breakdown(result):
    """
    Compare true fault classes against detector classifications.
    """
    faults = result[
        result["ground_truth_sensor_fault"]
    ].copy()

    print("\n" + "=" * 75)
    print("  ROOT-CAUSE / ANOMALY TYPE BREAKDOWN")
    print("=" * 75)

    if faults.empty:
        print("No sensor-fault observations found.")
        return

    true_counts = Counter(
        faults["ground_truth_label"]
    )

    predicted_counts = Counter(
        faults["predicted_anomaly_type"]
    )

    print("\nGround-truth sensor faults:")
    for label, count in true_counts.items():
        print(f"  {label:<28} {count}")

    print("\nDetector classifications on fault rows:")
    for label, count in predicted_counts.items():
        print(f"  {label:<28} {count}")


def print_sensor_identification(result):
    """
    Evaluate faulty-sensor identification only on rows where the
    benchmark specifies a sensor and the detector reports an anomaly.
    """
    rows = result[
        result["ground_truth_sensor_fault"]
        & result["ground_truth_faulty_sensor"].notna()
        & result["predicted_anomaly"]
        & result["predicted_faulty_sensor"].notna()
    ].copy()

    if rows.empty:
        print("\nNo comparable faulty-sensor predictions.")
        return

    # Normalize common naming differences.
    def normalize(value):
        value = str(value).strip().lower()

        aliases = {
            "temperature_c": "temperature",
            "temperature": "temperature",
            "pressure_hpa": "pressure",
            "pressure": "pressure",
            "humidity_pct": "humidity",
            "humidity": "humidity",
            "multivariate": "multivariate",
        }

        return aliases.get(value, value)

    true_sensor = rows[
        "ground_truth_faulty_sensor"
    ].map(normalize)

    pred_sensor = rows[
        "predicted_faulty_sensor"
    ].map(normalize)

    accuracy = float(
        np.mean(true_sensor.values == pred_sensor.values)
    )

    print("\n" + "=" * 75)
    print("  FAULTY SENSOR IDENTIFICATION")
    print("=" * 75)

    print(f"Comparable fault rows : {len(rows)}")
    print(
        f"Correct sensor        : "
        f"{int(np.sum(true_sensor.values == pred_sensor.values))}"
    )
    print(
        f"Sensor identification : "
        f"{accuracy * 100:.2f}%"
    )


def print_classification_report(result):
    """
    Classification report for sensor-fault vs normal.
    """
    y_true = result["ground_truth_sensor_fault"].astype(int)
    y_pred = result["predicted_anomaly"].astype(int)

    print("\n" + "=" * 75)
    print("  CLASSIFICATION REPORT")
    print("=" * 75)

    print(
        classification_report(
            y_true,
            y_pred,
            labels=[0, 1],
            target_names=["NORMAL / WEATHER", "SENSOR FAULT"],
            zero_division=0,
        )
    )


def save_results(result):
    output = os.path.join(
        PROJECT_DIR,
        "main_model_evaluation_results.csv",
    )

    result.to_csv(output, index=False)

    print("\n" + "=" * 75)
    print("  RESULTS SAVED")
    print("=" * 75)
    print(output)

    return output


def main():
    parser = argparse.ArgumentParser(
        description="Evaluate the AWSAnomalyDetector used by main.py."
    )

    parser.add_argument(
        "--file",
        type=str,
        default=None,
        help=(
            "Labeled benchmark CSV. If omitted, the benchmark is "
            "generated using AWSDataSimulator."
        ),
    )

    args = parser.parse_args()

    print("=" * 75)
    print("  SIH 2026 AWS MAIN.PY MODEL EVALUATION")
    print("=" * 75)

    if args.file:
        df = load_dataset(args.file)
        df = ensure_ground_truth(df)
    else:
        # This is the same benchmark-generation path used by main.py.
        df = generate_benchmark()

    print(
        f"[INFO] Dataset shape: {df.shape[0]} rows x "
        f"{df.shape[1]} columns"
    )

    reports = run_detector(df)

    result = reports_to_dataframe(
        df,
        reports,
    )

    metrics = print_detection_metrics(result)

    print_weather_event_metrics(result)
    print_anomaly_breakdown(result)
    print_sensor_identification(result)
    print_classification_report(result)

    output = save_results(result)

    print("\n" + "=" * 75)
    print("  FINAL SUMMARY")
    print("=" * 75)
    print(
        f"Accuracy : {metrics['accuracy'] * 100:.2f}%"
    )
    print(
        f"Precision: {metrics['precision'] * 100:.2f}%"
    )
    print(
        f"Recall   : {metrics['recall'] * 100:.2f}%"
    )
    print(
        f"F1       : {metrics['f1']:.4f}"
    )
    print(
        f"Caught   : {metrics['catch_rate']:.2f}%"
    )
    print(
        f"False Alarm Rate: "
        f"{metrics['false_alarm_rate']:.2f}%"
    )
    print(f"Results  : {output}")
    print("=" * 75)


if __name__ == "__main__":
    main()
